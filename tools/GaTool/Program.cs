// GaTool: build-time generator for Galactic Anarchy.
//
//   GaTool gen OUT_DIR MODELS_DIR
//       writes tables.inc, font.inc and models.inc (from the .model files in MODELS_DIR)
//       for the assembler
//   GaTool preview MODELS_DIR OUT.png
//       draws every model from the top, the front, the side and in perspective
//
// Everything the game needs that would be tedious or error-prone to type by hand is
// computed here: multiply and reciprocal tables, sine, screen addresses, the font and
// the models.

using System.Text;

if (args.Length == 3 && args[0] == "preview")
{
    try
    {
        Preview.Write(args[1], args[2]);
    }
    catch (ModelException e)
    {
        Console.Error.WriteLine(e.Message);
        return 1;
    }
    return 0;
}
if (args.Length != 3 || args[0] != "gen")
{
    Console.Error.WriteLine("usage: GaTool gen OUT_DIR MODELS_DIR | GaTool preview MODELS_DIR OUT.png");
    return 2;
}

var outDir = args[1];
Directory.CreateDirectory(outDir);
File.WriteAllText(Path.Combine(outDir, "tables.inc"), Tables.Generate());
File.WriteAllText(Path.Combine(outDir, "font.inc"), Font.Generate());
try
{
    File.WriteAllText(Path.Combine(outDir, "models.inc"), Models.Generate(args[2]));
}
catch (ModelException e)
{
    Console.Error.WriteLine(e.Message);
    return 1;
}
return 0;

static class Emit
{
    public static void Bytes(StringBuilder sb, string label, IEnumerable<int> values)
    {
        sb.AppendLine($"{label}:");
        var list = values.ToList();
        for (var i = 0; i < list.Count; i += 16)
        {
            var row = list.Skip(i).Take(16).Select(v =>
            {
                if (v < -128 || v > 255) throw new InvalidOperationException($"{label}[{i}] = {v} is not a byte");
                return $"${v & 0xFF:X2}";
            });
            sb.AppendLine("        .byte   " + string.Join(",", row));
        }
    }
}

static class Tables
{
    // Constants shared with the assembler (src/engine.inc repeats them; the build checks
    // nothing else, so keep the two in step).
    public const int ViewportTop = 0;           // bitmap pixel row of viewport line 0
    public const int ViewportLeftCells = 4;     // viewport starts at character column 4
    public const int ViewportLines = 160;
    public const int RecipEntries = 1024;       // indexed by z >> 2, z = 0..4095

    public static string Generate()
    {
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by tools/GaTool. Do not edit.");
        sb.AppendLine();

        // Quarter squares for the unsigned 8x8 multiply:
        //   sq1[i] = floor(i*i/4),        i = 0..511
        //   sq2[i] = floor((i-255)^2/4),  i = 0..511
        // a*b = sq1[a+b] - sq2[b-a+255]. Each table is 512 bytes, page aligned.
        // The TABLES segment runs at $9000 (cfg/game.cfg), so every table here starts on
        // a page boundary; main.s checks that at link time.
        sb.AppendLine("        .segment \"TABLES\"");
        var sq1 = Enumerable.Range(0, 512).Select(i => i * i / 4).ToArray();
        var sq2 = Enumerable.Range(0, 512).Select(i => (i - 255) * (i - 255) / 4).ToArray();
        Emit.Bytes(sb, "sq1_lo", sq1.Select(v => v & 0xFF));
        Emit.Bytes(sb, "sq1_hi", sq1.Select(v => v >> 8));
        Emit.Bytes(sb, "sq2_lo", sq2.Select(v => v & 0xFF));
        Emit.Bytes(sb, "sq2_hi", sq2.Select(v => v >> 8));

        // Signed quarter squares: f[i] = floor(n*n/4) for n = i - 256, i = 0..511. For any
        // signed a and b, a*b = f(a+b) - f(a-b) exactly (a+b and a-b have the same parity).
        var f = Enumerable.Range(0, 512).Select(i => (i - 256) * (i - 256) / 4).ToArray();
        Emit.Bytes(sb, "f_lo", f.Select(v => v & 0xFF));
        Emit.Bytes(sb, "f_hi", f.Select(v => v >> 8));

        // Perspective: recip[i] = min(255, round(32768 / z)) for z = 4*i, so that the
        // screen offset of a point is x * recip / 256 (a 90 degree field of view across
        // the 256-pixel viewport). Entries for z below the near plane are 255 and unused.
        var recip = Enumerable.Range(0, RecipEntries).Select(i =>
        {
            var z = i * 4;
            if (z == 0) return 255;
            return Math.Min(255, (int)Math.Round(32768.0 / z));
        });
        Emit.Bytes(sb, "recip", recip);

        sb.AppendLine();
        sb.AppendLine("        .segment \"RODATA\"");
        // Sine, signed, 256 steps per turn, amplitude 127. Cosine is sine + 64.
        var sine = Enumerable.Range(0, 256 + 64)
            .Select(i => (int)Math.Round(127 * Math.Sin(2 * Math.PI * i / 256)))
            .Select(v => v & 0xFF);
        Emit.Bytes(sb, "sine", sine);

        // Address of the first byte of each viewport line, relative to the bitmap start:
        // character row * 320 + line within the row + the viewport's left margin.
        // The column offset (x & $F8) is added through the Y register by the line drawer.
        var row = Enumerable.Range(0, ViewportLines).Select(y =>
        {
            var line = y + ViewportTop;
            return (line >> 3) * 320 + (line & 7) + ViewportLeftCells * 8;
        }).ToArray();
        Emit.Bytes(sb, "row_lo", row.Select(v => v & 0xFF));
        Emit.Bytes(sb, "row_hi", row.Select(v => v >> 8));

        // Pixel masks for x & 7, leftmost pixel = bit 7.
        Emit.Bytes(sb, "pixel_mask", Enumerable.Range(0, 8).Select(i => 0x80 >> i));
        return sb.ToString();
    }
}

static class Font
{
    // The game's own 8x8 font, glyphs 5 pixels wide and 7 tall in columns 1-5 and rows 0-6.
    // Row 7 of every glyph is empty: the raster split switches to text mode during the last
    // line of the viewport, and an empty row 7 keeps that line black.
    // Indexed by screen code: @=0, A-Z = 1-26, space = 32, digits = 48-57.
    public static readonly Dictionary<char, string[]> Glyphs = new()
    {
