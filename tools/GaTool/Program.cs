        ['5'] = ["#####", "#....", "####.", "....#", "....#", "#...#", ".###."],
        ['6'] = [".###.", "#....", "#....", "####.", "#...#", "#...#", ".###."],
        ['7'] = ["#####", "....#", "...#.", "..#..", "..#..", "..#..", "..#.."],
        ['8'] = [".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."],
        ['9'] = [".###.", "#...#", "#...#", ".####", "....#", "....#", ".###."],
        ['.'] = [".....", ".....", ".....", ".....", ".....", ".....", "..#.."],
        [':'] = [".....", "..#..", ".....", ".....", ".....", "..#..", "....."],
        ['-'] = [".....", ".....", ".....", ".###.", ".....", ".....", "....."],
        [' '] = [".....", ".....", ".....", ".....", ".....", ".....", "....."],
    };

    public static int ScreenCode(char c) => c switch
    {
        >= 'A' and <= 'Z' => c - 'A' + 1,
        _ => c,   // space, digits and the punctuation used here keep their ASCII codes
    };

    public static string Generate()
    {
        var data = new int[64 * 8];
        foreach (var (ch, rows) in Glyphs)
        {
            if (rows.Length != 7 || rows.Any(r => r.Length != 5))
                throw new InvalidOperationException($"glyph '{ch}' is not 5x7");
            var code = ScreenCode(ch);
            for (var y = 0; y < 7; y++)
            {
                var bits = 0;
                for (var x = 0; x < 5; x++)
                    if (rows[y][x] == '#') bits |= 0x40 >> x;
                data[code * 8 + y] = bits;
            }
        }
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by tools/GaTool. Do not edit.");
        sb.AppendLine("        .segment \"RODATA\"");
        Emit.Bytes(sb, "font", data);
        sb.AppendLine("FONT_SIZE = * - font");
        return sb.ToString();
    }
}

static class Models
{
    record Model(string Name, (int X, int Y, int Z)[] Vertices, (int A, int B)[] Edges);

    public static string Generate()
    {
        var models = new[] { Cube(100), Icosahedron(60, 97) };
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by tools/GaTool. Do not edit.");
        sb.AppendLine("; Per model: vertex count, edge count, then x/y/z arrays (signed bytes)");
        sb.AppendLine("; and the two vertex indices of each edge.");
        sb.AppendLine("        .segment \"RODATA\"");
        foreach (var m in models)
        {
            foreach (var v in m.Vertices)
                if (new[] { v.X, v.Y, v.Z }.Any(c => c < -127 || c > 127))
                    throw new InvalidOperationException($"{m.Name}: vertex out of range");
            sb.AppendLine($"MODEL_{m.Name.ToUpperInvariant()}_VERTS = {m.Vertices.Length}");
            sb.AppendLine($"MODEL_{m.Name.ToUpperInvariant()}_EDGES = {m.Edges.Length}");
            Emit.Bytes(sb, $"model_{m.Name}_x", m.Vertices.Select(v => v.X));
            Emit.Bytes(sb, $"model_{m.Name}_y", m.Vertices.Select(v => v.Y));
            Emit.Bytes(sb, $"model_{m.Name}_z", m.Vertices.Select(v => v.Z));
            Emit.Bytes(sb, $"model_{m.Name}_ea", m.Edges.Select(e => e.A));
            Emit.Bytes(sb, $"model_{m.Name}_eb", m.Edges.Select(e => e.B));
        }
        return sb.ToString();
    }

    static Model Cube(int s)
    {
        var v = new List<(int, int, int)>();
        for (var i = 0; i < 8; i++)
            v.Add(((i & 1) != 0 ? s : -s, (i & 2) != 0 ? s : -s, (i & 4) != 0 ? s : -s));
        var e = new List<(int, int)>();
        for (var a = 0; a < 8; a++)
            for (var bit = 1; bit < 8; bit <<= 1)
                if ((a & bit) == 0) e.Add((a, a | bit));
        return new Model("cube", v.ToArray(), e.ToArray());
    }

    // The regular icosahedron: cyclic permutations of (0, +-a, +-b) with b/a the golden ratio.
    // Edges join the vertices at the shortest distance, 2a.
    static Model Icosahedron(int a, int b)
    {
        var v = new List<(int X, int Y, int Z)>();
        foreach (var sa in new[] { -1, 1 })
            foreach (var sb in new[] { -1, 1 })
            {
                v.Add((0, sa * a, sb * b));
                v.Add((sa * a, sb * b, 0));
                v.Add((sb * b, 0, sa * a));
            }
        var e = new List<(int, int)>();
        long D2(int i, int j) =>
            (long)(v[i].X - v[j].X) * (v[i].X - v[j].X) + (long)(v[i].Y - v[j].Y) * (v[i].Y - v[j].Y)
            + (long)(v[i].Z - v[j].Z) * (v[i].Z - v[j].Z);
        var edge2 = 4L * a * a;
        for (var i = 0; i < v.Count; i++)
            for (var j = i + 1; j < v.Count; j++)
                if (Math.Abs(D2(i, j) - edge2) < edge2 / 10) e.Add((i, j));
        if (e.Count != 30) throw new InvalidOperationException($"icosahedron has {e.Count} edges, expected 30");
        return new Model("ico", v.Select(p => (p.X, p.Y, p.Z)).ToArray(), e.ToArray());
    }
}
