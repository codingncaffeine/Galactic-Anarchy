// The music compiler: reads music/*.music (format in music/tracks.music) and writes
// music.inc: the note frequency tables for PAL and NTSC, and per track and voice the
// sound settings and a note stream of (note, frames) pairs ending in $FF (loop) or $FE
// (stop). Note 0 is a rest; note n is semitone n - 1 above C0.

using System.Text;

static class Music
{
    sealed record Voice(int Wave, int Ad, int Sr, int Pw, List<(int Note, int Frames)> Notes);
    sealed record Track(string Name, bool Once, Voice?[] Voices);

    public static string Generate(string dir)
    {
        var tracks = new List<Track>();
        foreach (var file in Directory.GetFiles(dir, "*.music").OrderBy(f => f, StringComparer.Ordinal))
            tracks.AddRange(Parse(file));

        var sb = new StringBuilder();
        sb.AppendLine("; Generated by tools/GaTool from music/*.music. Do not edit.");
        sb.AppendLine("        .segment \"RODATA\"");
        // SID frequency = Hz * 2^24 / clock; A4 = 440 Hz, equal temperament.
        foreach (var (name, clock) in new[] { ("pal", 985248.0), ("ntsc", 1022727.0) })
        {
            // (The last notes of octave 7 lie above the SID's range; they are held at its top.)
            var f = Enumerable.Range(0, 96).Select(n =>
                Math.Min(0xFFFF, (int)Math.Round(440 * Math.Pow(2, (n - 57) / 12.0) * 16777216 / clock))).ToList();
            Emit.Bytes(sb, $"freq_{name}_lo", f.Select(v => v & 0xFF));
            Emit.Bytes(sb, $"freq_{name}_hi", f.Select(v => v >> 8));
        }

        for (var t = 0; t < tracks.Count; t++)
        {
            var tr = tracks[t];
            sb.AppendLine($"TRACK_{tr.Name.ToUpperInvariant()} = {t}");
            for (var v = 0; v < 2; v++)
            {
                var voice = tr.Voices[v];
                var bytes = new List<int>();
                if (voice is not null)
                    foreach (var (note, frames) in voice.Notes)
                    {
                        for (var left = frames; left > 0; left -= 255)
                        {
                            bytes.Add(left == frames ? note : 0);
                            bytes.Add(Math.Min(left, 255));
                        }
                    }
                bytes.Add(tr.Once || voice is null ? 0xFE : 0xFF);
                Emit.Bytes(sb, $"track_{tr.Name}_v{v + 1}", bytes);
            }
        }
        string Col(Func<Track, int, string> f) =>
            string.Join(", ", tracks.SelectMany(tr => new[] { f(tr, 0), f(tr, 1) }));
        sb.AppendLine($"TRACK_COUNT = {tracks.Count}");
        sb.AppendLine("; per track, voice 1 then voice 2:");
        sb.AppendLine($"track_lo:       .byte {Col((tr, v) => $"<track_{tr.Name}_v{v + 1}")}");
        sb.AppendLine($"track_hi:       .byte {Col((tr, v) => $">track_{tr.Name}_v{v + 1}")}");
        sb.AppendLine($"track_wave:     .byte {Col((tr, v) => (tr.Voices[v]?.Wave ?? 0).ToString())}");
        sb.AppendLine($"track_ad:       .byte {Col((tr, v) => (tr.Voices[v]?.Ad ?? 0).ToString())}");
        sb.AppendLine($"track_sr:       .byte {Col((tr, v) => (tr.Voices[v]?.Sr ?? 0).ToString())}");
        sb.AppendLine($"track_pw_lo:    .byte {Col((tr, v) => ((tr.Voices[v]?.Pw ?? 0) & 0xFF).ToString())}");
        sb.AppendLine($"track_pw_hi:    .byte {Col((tr, v) => ((tr.Voices[v]?.Pw ?? 0) >> 8).ToString())}");
        return sb.ToString();
    }

    static IEnumerable<Track> Parse(string file)
    {
        var result = new List<Track>();
        Track? track = null;
        int voice = -1;
        var lineNo = 0;
        foreach (var raw in File.ReadLines(file))
        {
            lineNo++;
            var line = raw.Trim();
            if (line.StartsWith('#')) continue;     // a comment; a # elsewhere is a sharp
            line = line.Replace("|", " ");
            if (line.Length == 0) continue;
            var t = line.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            string Where() => $"{Path.GetFileName(file)}:{lineNo}";
            if (t[0] == "track")
            {
                Check(track, Where);
                track = new Track(t[1], t.Length > 2 && t[2] == "once", new Voice?[2]);
                result.Add(track);
                voice = -1;
                continue;
            }
            if (track is null) throw new ModelException($"{Where()}: 'track' expected first");
            if (t[0] is "v1" or "v2")
            {
                if (t.Length != 5) throw new ModelException($"{Where()}: vN WAVE AD SR PW");
                var wave = t[1] switch
                {
                    "tri" => 0x10, "saw" => 0x20, "pulse" => 0x40, "noise" => 0x80,
                    _ => throw new ModelException($"{Where()}: wave is tri, saw, pulse or noise"),
                };
                voice = t[0][1] - '1';
                track.Voices[voice] = new Voice(wave, Convert.ToInt32(t[2], 16), Convert.ToInt32(t[3], 16),
                    Convert.ToInt32(t[4], 16), []);
                continue;
            }
            if (voice < 0) throw new ModelException($"{Where()}: notes before a voice line");
            foreach (var tok in t)
            {
                var parts = tok.Split('/');
                if (parts.Length != 2 || !int.TryParse(parts[1], out var frames) || frames <= 0)
                    throw new ModelException($"{Where()}: '{tok}' is not NOTE/FRAMES");
                track.Voices[voice]!.Notes.Add((NoteNumber(parts[0], Where), frames));
            }
        }
        Check(track, () => file);
        return result;
    }

    static void Check(Track? track, Func<string> where)
    {
        if (track is null) return;
        var lengths = track.Voices.Where(v => v is not null).Select(v => v!.Notes.Sum(n => n.Frames)).Distinct().ToList();
        if (lengths.Count > 1)
            throw new ModelException($"{where()}: track {track.Name}: voices differ in length ({string.Join(", ", lengths)} frames)");
    }

    static int NoteNumber(string s, Func<string> where)
    {
        if (s == "R") return 0;
        var names = new[] { "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B" };
        var octave = s[^1] - '0';
        var idx = Array.IndexOf(names, s[..^1]);
        if (idx < 0 || octave is < 0 or > 7) throw new ModelException($"{where()}: '{s}' is not a note");
        return octave * 12 + idx + 1;
    }
}
